import { pgTable, uuid, text, varchar, integer, timestamp, date } from "drizzle-orm/pg-core";
import { leadStatus, slaResponseStatus } from "../enums";

export const leads = pgTable("leads", {
  id: uuid("id").primaryKey().defaultRandom(),
  fullName: text("full_name"),
  email: varchar("email", { length: 255 }),
  phone: varchar("phone", { length: 50 }),
  company: text("company"),
  country: varchar("country", { length: 100 }),
  budget: text("budget"),
  timeline: text("timeline"),
  projectType: text("project_type"),
  inquiryType: varchar("inquiry_type", { length: 50 }),
  message: text("message"),
  leadSource: varchar("lead_source", { length: 50 }),
  status: leadStatus("status").default("new"),
  assignedUserId: uuid("assigned_user_id"),
  followUpDate: date("follow_up_date"),
  followUpNotes: text("follow_up_notes"),
  convertedToProjectId: uuid("converted_to_project_id"),
  convertedToEventId: uuid("converted_to_event_id"),
  utmSource: varchar("utm_source", { length: 255 }),
  utmMedium: varchar("utm_medium", { length: 255 }),
  utmCampaign: varchar("utm_campaign", { length: 255 }),
  utmContent: varchar("utm_content", { length: 255 }),
  utmTerm: varchar("utm_term", { length: 255 }),
  slaMinutes: integer("sla_minutes").default(15),
  firstResponseAt: timestamp("first_response_at", { withTimezone: true }),
  responseStatus: slaResponseStatus("response_status"),
  createdBy: uuid("created_by"),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow(),
});
