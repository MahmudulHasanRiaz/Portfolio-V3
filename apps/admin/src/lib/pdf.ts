import PDFDocument from "pdfkit";
import { initR2, buildKey, generatePresignedUploadUrl, getPublicUrl } from "@repo/media";
import type { Env } from "@repo/shared";
import type { FinanceInvoiceRow } from "@repo/finance";
import type { ProposalDocumentRow } from "@repo/proposals";

// ─── PDF rendering helpers ───────────────────────────────────────────────────

function renderPdf(build: (doc: InstanceType<typeof PDFDocument>) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    try {
      build(doc);
    } catch (err) {
      reject(err);
      return;
    }
    doc.end();
  });
}

function money(value: string | number | null | undefined): string {
  const num = Number(value ?? 0);
  return Number.isNaN(num) ? "0.00" : num.toFixed(2);
}

// ─── Invoice PDF ─────────────────────────────────────────────────────────────

export async function generateInvoicePdf(
  invoice: FinanceInvoiceRow,
  clientName?: string,
): Promise<Buffer> {
  const currency = invoice.currency ?? "BDT";
  const items = invoice.lineItems ?? [];

  return renderPdf((doc) => {
    doc.fontSize(24).font("Helvetica-Bold").text("INVOICE");
    doc.moveDown(0.5);
    doc.fontSize(11).font("Helvetica");
    doc.text(`Invoice Number: ${invoice.invoiceNumber ?? invoice.id}`);
    if (clientName) doc.text(`Billed To: ${clientName}`);
    else if (invoice.clientId) doc.text(`Client ID: ${invoice.clientId}`);
    if (invoice.issuedDate) doc.text(`Issued: ${invoice.issuedDate}`);
    if (invoice.dueDate) doc.text(`Due: ${invoice.dueDate}`);
    doc.text(`Status: ${invoice.status ?? "draft"}`);
    doc.moveDown(1);

    // Line items table
    const startX = 50;
    const qtyX = 340;
    const priceX = 400;
    const totalX = 480;
    const rowEndX = 562;

    doc.font("Helvetica-Bold").fontSize(10);
    doc.text("Description", startX, doc.y, { continued: false });
    const headerY = doc.y - 12;
    doc.text("Qty", qtyX, headerY);
    doc.text("Unit Price", priceX, headerY);
    doc.text("Total", totalX, headerY);
    doc.moveTo(startX, headerY + 16).lineTo(rowEndX, headerY + 16).stroke();
    doc.font("Helvetica");
    doc.y = headerY + 22;

    for (const item of items) {
      const y = doc.y;
      doc.text(item.description || "-", startX, y, { width: qtyX - startX - 10 });
      doc.text(String(item.quantity), qtyX, y);
      doc.text(money(item.unitPrice), priceX, y);
      doc.text(money(item.total), totalX, y);
      doc.y = y + 16;
    }

    doc.moveTo(startX, doc.y + 4).lineTo(rowEndX, doc.y + 4).stroke();
    doc.moveDown(1);

    const labelX = 380;
    doc.text(`Subtotal:`, labelX, doc.y, { continued: true }).text(` ${money(invoice.subtotal)} ${currency}`, totalX - 80);
    if (Number(invoice.discount ?? 0) !== 0) {
      doc.text(`Discount:`, labelX, doc.y, { continued: true }).text(` ${money(invoice.discount)} ${currency}`, totalX - 80);
    }
    doc.font("Helvetica-Bold");
    doc.text(`Total:`, labelX, doc.y, { continued: true }).text(` ${money(invoice.total)} ${currency}`, totalX - 80);
    doc.font("Helvetica");

    if (currency !== "BDT" && invoice.totalBdt) {
      doc.moveDown(0.5);
      doc.text(
        `Total in BDT: ${money(invoice.totalBdt)} BDT` +
          (invoice.exchangeRate ? ` (exchange rate: ${invoice.exchangeRate})` : ""),
        labelX,
      );
    }

    if (invoice.notes) {
      doc.moveDown(1.5);
      doc.fontSize(10).text(`Notes: ${invoice.notes}`);
    }

    doc.moveDown(2);
    doc.fontSize(9).fillColor("#666666").text("Generated by Portfolio V2 — Personal Brand Platform.");
  });
}

// ─── Proposal PDF ────────────────────────────────────────────────────────────

export async function generateProposalPdf(
  document: ProposalDocumentRow,
  templateName?: string,
): Promise<Buffer> {
  const title = templateName ?? "Proposal";

  return renderPdf((doc) => {
    doc.fontSize(22).font("Helvetica-Bold").text(title);
    doc.moveDown(0.5);
    doc.fontSize(11).font("Helvetica");
    doc.text(`Version: ${document.version}`);
    doc.text(`Status: ${document.status ?? "draft"}`);
    if (document.sentAt) doc.text(`Sent: ${document.sentAt}`);
    doc.moveDown(1);

    doc.fontSize(11).text(document.resolvedContent ?? "", {
      align: "left",
      lineGap: 4,
    });

    if (document.status === "rejected" && document.rejectionReason) {
      doc.moveDown(1.5);
      doc.fontSize(10).text(`Rejection reason: ${document.rejectionReason}`);
    }

    doc.moveDown(2);
    doc.fontSize(9).fillColor("#666666").text("Generated by Portfolio V2 — Personal Brand Platform.");
  });
}

// ─── R2 storage ──────────────────────────────────────────────────────────────

let r2Initialized = false;

function ensureR2Initialized(): void {
  if (r2Initialized) return;
  const { R2_ENDPOINT, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET, R2_PUBLIC_URL } = process.env;
  if (!R2_ENDPOINT || !R2_ACCESS_KEY_ID || !R2_SECRET_ACCESS_KEY || !R2_BUCKET) {
    throw new Error(
      "R2 storage is not configured: R2_ENDPOINT, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY and R2_BUCKET must be set to store PDFs.",
    );
  }
  initR2({
    R2_ENDPOINT,
    R2_ACCESS_KEY_ID,
    R2_SECRET_ACCESS_KEY,
    R2_BUCKET,
    R2_PUBLIC_URL,
  } as Env);
  r2Initialized = true;
}

/**
 * Stores a generated PDF in R2 under the "documents/" prefix and returns its
 * public URL. Uploads through a presigned PUT URL because @repo/media does
 * not export the raw uploadFile primitive from its package index.
 */
export async function storePdf(buffer: Buffer, filename: string): Promise<string> {
  ensureR2Initialized();
  const key = buildKey("documents", filename);
  const uploadUrl = await generatePresignedUploadUrl(key, "application/pdf");
  const response = await fetch(uploadUrl, {
    method: "PUT",
    headers: { "Content-Type": "application/pdf" },
    body: new Uint8Array(buffer),
  });
  if (!response.ok) {
    throw new Error(`Failed to upload PDF to R2 (status ${response.status})`);
  }
  return getPublicUrl(key);
}
