// Icon sprite generator — replaces ~46 cdn.simpleicons.org requests
// (one per brand icon) with ONE self-hosted hashed SVG sprite.
//
// Run automatically before every build (`prebuild` in package.json),
// and committed to the repo so `astro dev` works without running it.
// The sprite only covers the Simple Icons slugs actually used in
// src/data/site.ts (plus any hardcoded simpleIconsUrl("...") calls).
// A slug NOT in the sprite (e.g. a new icon from the live API) falls
// back to the CDN <img> at render time — see src/lib/icons.ts and
// BrandIcon.astro — so the site never renders a blank icon.
//
// Output:
//   src/assets/icons.svg — <symbol> per icon, path filled with the
//     brand hex (matches what cdn.simpleicons.org/<slug> served).
//   src/lib/icons.ts — ICON_SPRITE_URL (?url import, content-hashed
//     by Vite, immutable) + SPRITE_SLUGS set for the fallback check.
//
// Regenerate by hand: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const siteTs = readFileSync(join(root, "src/data/site.ts"), "utf8");

// Collect every Simple Icons slug the site can render: `icon: "slug"`
// in the data file (STACK / SERVICES / PLATFORMS) plus any hardcoded
// simpleIconsUrl("slug") call elsewhere in src/.
const slugs = new Set();
for (const m of siteTs.matchAll(/icon:\s*"([^"]+)"/g)) {
	const v = m[1];
	if (v.startsWith("wikimedia:") || v === "woocommerce-w") continue;
	slugs.add(v);
}
for (const m of siteTs.matchAll(/simpleIconsUrl\("([^"]+)"\)/g)) {
	slugs.add(m[1]);
}

const bySlug = new Map();
for (const icon of Object.values(simpleIcons)) {
	if (icon && typeof icon === "object" && "slug" in icon) {
		bySlug.set(icon.slug, icon);
	}
}

const missing = [];
const symbols = [];
for (const slug of [...slugs].sort()) {
	const icon = bySlug.get(slug);
	if (!icon) {
		missing.push(slug);
		continue;
	}
	// Escape once: simple-icons paths are [0-9a-zA-Z.,\- ] only, but
	// never trust a third-party string inside an attribute unescaped.
	const path = String(icon.path).replace(/"/g, "&quot;");
	symbols.push(
		`<symbol id="${slug}" viewBox="0 0 24 24"><path d="${path}" fill="#${icon.hex}"/></symbol>`,
	);
}
if (missing.length > 0) {
	console.warn(
		`[generate-icons] WARNING: ${missing.length} slug(s) not in simple-icons ${process.env.npm_package_version ?? ""} — they will fall back to the CDN at render time: ${missing.join(", ")}`,
	);
}

mkdirSync(join(root, "src/assets"), { recursive: true });
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">\n${symbols.join("\n")}\n</svg>\n`;
writeFileSync(join(root, "src/assets/icons.svg"), sprite, "utf8");

const libTs = `// GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// One self-hosted SVG sprite for every Simple Icons slug the site
// renders (see src/assets/icons.svg). Imported with ?url so Vite
// emits it content-hashed under /_astro/ (immutable, long cache).
// A slug missing here falls back to the CDN <img> — see BrandIcon.
import spriteUrl from "../assets/icons.svg?url";

export const ICON_SPRITE_URL: string = spriteUrl;

/** Slugs present in the sprite (sorted). */
export const SPRITE_SLUGS: ReadonlySet<string> = new Set(${JSON.stringify(
	[...slugs].sort().filter((s) => bySlug.has(s)),
)});

export function hasSpriteIcon(slug: string): boolean {
	return SPRITE_SLUGS.has(slug);
}
`;
writeFileSync(join(root, "src/lib/icons.ts"), libTs, "utf8");

console.log(
	`[generate-icons] ${symbols.length} icon(s) → src/assets/icons.svg (${(Buffer.byteLength(sprite) / 1024).toFixed(1)} KiB) + src/lib/icons.ts`,
);
